create table if not exists public.fantasy_team_mlb_affiliates (
  id bigint generated by default as identity primary key,
  fantasy_team_id bigint not null references public.fantasy_teams(id) on delete cascade,
  season_year integer not null check (season_year >= 2026),
  slot smallint not null check (slot in (1, 2)),
  mlb_team_id integer not null,
  mlb_team_name text not null,
  unique (fantasy_team_id, season_year, slot)
);

create table if not exists public.mlb_initial_signings (
  id bigint generated by default as identity primary key,
  player_api_id text,
  player_name text not null,
  birth_date date,
  position text,
  mlb_team_id integer not null,
  mlb_team_name text not null,
  signing_year integer not null,
  signing_type text not null check (signing_type in ('UDFA', 'INTERNATIONAL', 'OTHER')),
  unique (player_name, mlb_team_id, signing_year)
);

alter table public.fantasy_team_mlb_affiliates enable row level security;
alter table public.mlb_initial_signings enable row level security;
drop policy if exists "Public can read MLB affiliates" on public.fantasy_team_mlb_affiliates;
create policy "Public can read MLB affiliates" on public.fantasy_team_mlb_affiliates for select using (true);
drop policy if exists "Public can read MLB initial signings" on public.mlb_initial_signings;
create policy "Public can read MLB initial signings" on public.mlb_initial_signings for select using (true);

do $$
declare
  selected_season integer;
begin
  for selected_season in 2026..2027 loop
    insert into public.fantasy_team_mlb_affiliates (fantasy_team_id, season_year, slot, mlb_team_id, mlb_team_name)
    select team.id, selected_season, source.slot, source.mlb_team_id, source.mlb_team_name
    from (values
      ('OCB', 1, 138, 'St. Louis Cardinals'), ('OCB', 2, 110, 'Baltimore Orioles'),
      ('STM', 1, 133, 'Athletics'), ('STM', 2, 140, 'Texas Rangers'),
      ('BBS', 1, 136, 'Seattle Mariners'), ('BBS', 2, 135, 'San Diego Padres'),
      ('MCW', 1, 113, 'Cincinnati Reds'), ('MCW', 2, 158, 'Milwaukee Brewers'),
      ('DBG', 1, 115, 'Colorado Rockies'), ('DBG', 2, 145, 'Chicago White Sox'),
      ('TEX', 1, 147, 'New York Yankees'), ('TEX', 2, 142, 'Minnesota Twins'),
      ('LBO', 1, 109, 'Arizona Diamondbacks'), ('LBO', 2, 139, 'Tampa Bay Rays'),
      ('SSV', 1, 119, 'Los Angeles Dodgers'), ('SSV', 2, 141, 'Toronto Blue Jays'),
      ('WAR', 1, 117, 'Houston Astros'), ('WAR', 2, 114, 'Cleveland Guardians')
    ) as source(abbreviation, slot, mlb_team_id, mlb_team_name)
    join public.fantasy_teams team on team.abbreviation = source.abbreviation
    on conflict (fantasy_team_id, season_year, slot) do update
      set mlb_team_id = excluded.mlb_team_id, mlb_team_name = excluded.mlb_team_name;
  end loop;
end $$;

