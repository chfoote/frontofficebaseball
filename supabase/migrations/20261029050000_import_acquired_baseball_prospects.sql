create table if not exists public.mlb_acquired_prospect_rights (
  id bigint generated by default as identity primary key,
  season_year integer not null,
  player_name text not null,
  fantasy_team_id bigint not null references public.fantasy_teams(id) on delete cascade,
  acquisition_note text,
  unique (season_year, player_name)
);

alter table public.mlb_acquired_prospect_rights enable row level security;
drop policy if exists "Public can read acquired MLB prospect rights" on public.mlb_acquired_prospect_rights;
